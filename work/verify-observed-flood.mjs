import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {parseRadarCapabilities,parseNasaCapabilities,classifyRadarPixel,loadObservedFlood,loadRadarPoint} from './somalia-flood-watch/observed-flood.mjs';
const now = new Date('2026-10-13T09:15:00Z');
const radarXml = await readFile(new URL('./observed-gfm-capabilities.xml',import.meta.url),'utf8');
const nasaXml = await readFile(new URL('./observed-gibs-capabilities.xml',import.meta.url),'utf8');
const radar = parseRadarCapabilities(radarXml,now);
const nasa = parseNasaCapabilities(nasaXml,now);
assert.equal(radar.timeDefault,'2026-10-12');
assert.equal(radar.sourceTimeDefault,'2026-10-13');
assert.ok(radar.availableDates.includes('2026-10-13'));
assert.equal(radar.partial,false);
assert.equal(nasa.timeDefault,'2026-10-12');
assert.equal(nasa.compositeStart,'2026-10-10');
assert.throws(()=>parseRadarCapabilities('<xml/>',now));
assert.throws(()=>parseNasaCapabilities('<xml/>',now));
assert.equal(classifyRadarPixel(1,0,0,true),'flood-detected');
assert.equal(classifyRadarPixel(0,0,0,true),'no-flood-detected');
assert.equal(classifyRadarPixel(0,1,0,true),'unknown');
assert.equal(classifyRadarPixel(0,0,1,true),'reference-water');
assert.equal(classifyRadarPixel(1,0,0,false),'unknown');
assert.equal(classifyRadarPixel(255,0,0,true),'unknown');
assert.equal(classifyRadarPixel(0,null,0,true),'unknown');
assert.equal(classifyRadarPixel(0,0,null,true),'unknown');
assert.equal(classifyRadarPixel(1,null,0,true),'unknown');
assert.equal(classifyRadarPixel(1,0,null,true),'unknown');
const response = content => ({ok:true,status:200,text:async()=>content,json:async()=>content});
const metadataFetch = async url => response(String(url).includes('geoserver.gfm')?radarXml:nasaXml);
const source = await loadObservedFlood({fetchImpl:metadataFetch,now});
assert.equal(source.primary,'radar');
assert.equal(source.radar.resolutionM,20);
assert.equal(source.nasa.maxNativeZoom,9);
assert.equal(source.radar.legend[0].color,'#e84c78');
assert.equal(source.nasa.legend.find(x=>x.value===255).label,'Insufficient Data');
const oneSourceFetch = async url => {if(String(url).includes('geoserver.gfm'))throw new Error('unavailable');return response(nasaXml);};
const fallback = await loadObservedFlood({fetchImpl:oneSourceFetch,now});
assert.equal(fallback.primary,'nasa');
assert.equal(fallback.radar.available,false);
assert.equal(fallback.nasa.available,true);
const footprint = {features:[{properties:{sensing_date:'2026-10-12T02:46:03Z',anomaly_detected:false,flooded_pixels:1234}},{properties:{sensing_date:'2026-10-12T02:46:03Z',anomaly_detected:false}}]};
const pointFetch = (mask,hasScene=true) => async url => {
  const parsed = new URL(url);
  assert.equal(parsed.hostname,'geoserver.gfm.eodc.eu');
  assert.equal(parsed.searchParams.get('TIME'),'2026-10-12T00:00:00Z/2026-10-12T23:59:59Z');
  const layer = parsed.searchParams.get('LAYERS');
  if(layer.endsWith('_footprint')) return response(hasScene?footprint:{features:[]});
  return response({features:[{properties:{GRAY_INDEX:layer.endsWith('exclusion_mask')?mask:0}}]});
};
const city = await loadRadarPoint(2.0469,45.3182,'2026-10-12',{fetchImpl:pointFetch(1),now});
assert.equal(city.pixel.classification,'unknown');
assert.equal(city.pixel.excluded,true);
assert.equal(city.scenes.length,1);
assert.equal(city.latestSensingDate,'2026-10-12T02:46:03Z');
assert.equal(city.scenes[0].flooded_pixels,undefined);
const clearPixel = await loadRadarPoint(2.0469,45.3182,'2026-10-12',{fetchImpl:pointFetch(0),now});
assert.equal(clearPixel.pixel.classification,'no-flood-detected');
assert.match(clearPixel.note,/not an all-clear/);
const unobserved = await loadRadarPoint(2.0469,45.3182,'2026-10-12',{fetchImpl:pointFetch(0,false),now});
assert.equal(unobserved.coverage,'no-recent-scene');
assert.equal(unobserved.pixel.classification,'unknown');
const malformedFetch = async ()=>response({unexpected:'data'});
const malformed = await loadRadarPoint(2.0469,45.3182,'2026-10-12',{fetchImpl:malformedFetch,now});
assert.equal(malformed.coverage,'unavailable');
assert.equal(malformed.available,false);
const futureFootprintFetch = async url => String(url).includes('_footprint') ? response({features:[{properties:{sensing_date:'2026-10-14T01:00:00Z'}}]}) : pointFetch(0)(url);
const future = await loadRadarPoint(2.0469,45.3182,'2026-10-12',{fetchImpl:futureFootprintFetch,now});
assert.equal(future.scenes.length,0);
assert.equal(future.pixel.classification,'unknown');
await assert.rejects(()=>loadRadarPoint(100,45,'2026-10-12',{fetchImpl:pointFetch(0),now}));
await assert.rejects(()=>loadRadarPoint(2,45,'2026-10-14',{fetchImpl:pointFetch(0),now}));
await assert.rejects(()=>loadRadarPoint(2,45,'2026-10-12junk',{fetchImpl:pointFetch(0),now}));
console.log('Observed flood API checks passed: dates, radar masks, unknown coverage, source fallback, and no city-level scene totals.');
