import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const ids=['daily-title','daily-city','daily-date-tabs','daily-summary','hourly-chart','hourly-detail','hourly-table','daily-status','hourly-export','meteoblue-link'];
const nodes=Object.fromEntries(ids.map(id=>[id,{id,innerHTML:'',textContent:'',className:'',classList:{add(){}},querySelector(){return null},removeAttribute(name){delete this[name]}}]));
let download;
const sandbox={window:{},document:{getElementById(id){return nodes[id]},createElement(){return {click(){download=this}}}},Blob,URL:{createObjectURL(){return 'blob:test'},revokeObjectURL(){}},setTimeout(){},Date};
vm.runInNewContext(fs.readFileSync(new URL('./somalia-flood-watch/dist/daily.js',import.meta.url),'utf8'),sandbox,{filename:'daily.js'});
const {dayData,hourData,weatherInfo,render}=sandbox.window.DailyWeather;
const date='2026-10-13';
const forecast={timezone:'Africa/Mogadishu',utc_offset_seconds:10800,daily:{time:['2026-10-12',date,'2026-10-14'],temperature_2m_max:[12,32,null],temperature_2m_min:[9,22,null],weather_code:[61,0,null],precipitation_sum:[40,0,null],precipitation_probability_max:[100,0,null],sunrise:['2026-10-12T05:40',date+'T05:40',null],sunset:[null,date+'T17:45',null],uv_index_max:[null,8.5,null]},hourly:{time:['2026-10-12T01:00',date+'T00:00',date+'T01:00',date+'T03:00','2026-10-14T00:00'],temperature_2m:[999,0,26,30,888],precipitation:[999,0,1.5,0,888],weather_code:[95,0,61,3,95],is_day:[1,0,0,1,1],wind_direction_10m:[0,0,360,90,0],visibility:[null,10000,null,4000,null]}};
assert.equal(dayData(forecast,date).temperature_2m_max,32,'Daily data matches the date, not selected-day index');
assert.equal(dayData(forecast,date).precipitation_sum,0,'Zero rain is a valid measurement');
assert.equal(dayData(forecast,date).sourceTime,date);
assert.equal(dayData(forecast,'2026-10-15').temperature_2m_max,null);
assert.equal(dayData(null,date).weather_code,null);
assert.equal(dayData({daily:{time:[date],sunrise:['2026-10-14T05:40']}},date).sunrise,null,'Reject sun times for the wrong day');
assert.equal(dayData({daily:{time:[date],temperature_2m_max:['32']}},date).temperature_2m_max,null,'Do not coerce strings to model values');
const hours=hourData(forecast,date);
assert.equal(hours.length,24);
assert.equal(hours[0].temperature_2m,0);
assert.equal(hours[0].time,date+'T00:00');
assert.equal(hours[1].index,2);
assert.equal(hours[2].temperature_2m,null);
assert.equal(hours[2].time,null,'Do not fabricate a source timestamp for an absent hour');
assert.equal(hours[3].temperature_2m,30);
assert.equal(hours[23].temperature_2m,null);
assert.equal(hourData({hourly:{time:[date+'T24:00',date+'T02:30',date+'T02:00Z'],temperature_2m:[2,3,4]}},date).filter(row=>row.index>=0).length,0);
assert.equal(weatherInfo(0,0).label,'Clear night');
assert.equal(weatherInfo(0,1).label,'Clear sky');
assert.equal(weatherInfo(null).kind,'unknown');
assert.equal(weatherInfo(99).kind,'thunder');
assert.equal(weatherInfo(48).kind,'fog');
assert.equal(weatherInfo(82).label,'Violent rain showers');
assert.ok(weatherInfo(61).icon.includes('viewBox="0 0 72 72"'));
let selectedDay,selectedHour;
const state={city:{name:'Galkayo',region:'Mudug'},date,days:[date,'2026-10-14'],forecast,loadedAt:'2026-10-13T06:10:00Z',selectedHour:0,loading:false,error:null,stale:false,onDay(index){selectedDay=index},onHour(hour){selectedHour=hour}};
render(state);
assert.ok(nodes['daily-summary'].innerHTML.includes('0.0 <small>mm</small>'));
assert.ok(nodes['daily-summary'].innerHTML.includes('Daily rainfall screening only'),'Rainfall is not presented as a confirmed flood impact');
assert.equal((nodes['hourly-chart'].innerHTML.match(/<polyline /g)||[]).length,2,'Temperature gaps create separate line segments');
assert.ok(!nodes['hourly-chart'].innerHTML.includes('NaN'));
assert.ok(nodes['daily-status'].innerHTML.includes('3/24 temperatures'));
assert.ok(nodes['hourly-detail'].innerHTML.includes('10.0 <small>km</small>'),'Visibility uses km in UI');
assert.equal((nodes['hourly-table'].innerHTML.match(/<tr>/g)||[]).length,25,'Table has one header and 24 hourly rows');
assert.equal(nodes['meteoblue-link'].hidden,false);
assert.equal(nodes['meteoblue-link'].href,'https://www.meteoblue.com/en/weather/today/gaalkacyo_somalia_59611');
assert.ok(nodes['daily-status'].innerHTML.includes('Open-Meteo weather model forecast'));
assert.ok(!nodes['daily-summary'].innerHTML.includes('meteoblue'));
nodes['daily-city'].tagName='SELECT';
nodes['daily-city'].textContent='Mogadishu Galkayo';
nodes['daily-city'].value='10';
render(state);
assert.equal(nodes['daily-city'].textContent,'Mogadishu Galkayo','Renderer preserves the city select options');
assert.equal(nodes['daily-city'].value,'10','The parent owns the city select value');
nodes['daily-date-tabs'].onclick({target:{closest(){return {dataset:{wxDay:'1'}}}}});
assert.equal(selectedDay,1);
nodes['hourly-chart'].onclick({target:{closest(){return {dataset:{wxHour:'3'}}}}});
assert.equal(selectedHour,3);
const csv=await nodes['hourly-export'].onclick().text();
assert.equal(csv.split('\r\n').length,25);
assert.ok(csv.includes('"2026-10-13T00:00"'));
assert.ok(!csv.includes('"2026-10-13T02:00"'),'Missing hours have no invented source timestamp');
assert.ok(download.download.includes('Galkayo-'+date));
assert.ok(csv.includes('"10000"'),'CSV preserves visibility in source units, metres');
render({...state,city:{name:'Mogadishu',region:'Banaadir'},forecast:null,error:'<upstream unavailable>'});
assert.equal(nodes['meteoblue-link'].hidden,true);
assert.equal(nodes['hourly-export'].disabled,true);
assert.ok(nodes['daily-status'].innerHTML.includes('&lt;upstream unavailable&gt;'));
assert.ok(!nodes['hourly-chart'].innerHTML.includes('NaN'));
console.log('daily.js: helper, rendering, date alignment, chart gap, select preservation, callback and CSV assertions passed.');
